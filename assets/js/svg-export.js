/**
 * SVG Export Module for Freight Signs Customizer
 * Generates production-ready SVG files that match client export format
 * 
 * Key Features:
 * - Proper viewBox and dimensions
 * - ClipPath support for complex shapes
 * - Text to path conversion for font consistency
 * - Material/texture embedding
 * - Clean XML structure
 */

(function() {
    'use strict';

    window.FSC_SVGExport = {
        /**
         * Export the current design as a production-ready SVG
         * @param {Object} options - Export options
         * @returns {Promise<string>} SVG content as string
         */
        exportDesign: async function(options = {}) {
            console.log('🎨 Starting SVG export...', options);
            
            const defaults = {
                width: 600,           // Default width in pixels
                height: 450,          // Default height in pixels
                dpi: 300,             // For print: 300 DPI
                includeBackground: true,
                convertTextToPaths: false, // Set true for production
                embedFonts: true,
                format: 'svg',        // 'svg' or 'pdf' (future)
                colorMode: 'rgb'      // 'rgb' or 'cmyk' (future)
            };
            
            const config = { ...defaults, ...options };
            
            try {
                // Get the preview area
                const previewArea = document.querySelector('.apd-template-preview, .fsc-preview-content');
                if (!previewArea) {
                    throw new Error('Preview area not found');
                }
                
                // Get logo and text elements
                const logoContainer = previewArea.querySelector('.fsc-logo-container, .apd-logo-box');
                const textContainer = previewArea.querySelector('.fsc-text-container, .apd-text-layer');
                
                // Start building the SVG
                const svgContent = await this._buildProductionSVG({
                    logoContainer,
                    textContainer,
                    config
                });
                
                console.log('✅ SVG export complete');
                return svgContent;
                
            } catch (error) {
                console.error('❌ SVG export failed:', error);
                throw error;
            }
        },
        
        /**
         * Build production-ready SVG with proper structure
         */
        _buildProductionSVG: async function({ logoContainer, textContainer, config }) {
            const { width, height, dpi } = config;
            
            // Add padding to prevent clipping (10% on each side)
            const paddingPercent = 0.1; // 10% padding
            const paddedWidth = width * (1 + paddingPercent * 2);
            const paddedHeight = height * (1 + paddingPercent * 2);
            
            // Calculate viewBox for high resolution with padding
            const viewBoxWidth = paddedWidth * (dpi / 96); // 96 is screen DPI
            const viewBoxHeight = paddedHeight * (dpi / 96);
            
            // Start SVG with proper XML declaration
            let svg = `<?xml version="1.0" encoding="UTF-8"?>\n`;
            svg += `<!DOCTYPE svg PUBLIC "-//W3C//DTD SVG 1.1//EN" "http://www.w3.org/Graphics/SVG/1.1/DTD/svg11.dtd">\n`;
            svg += `<!-- Generated by Freight Signs Customizer -->\n`;
            svg += `<svg xmlns="http://www.w3.org/2000/svg"`;
            svg += ` xmlns:xlink="http://www.w3.org/1999/xlink"`;
            svg += ` width="${paddedWidth}px" height="${paddedHeight}px"`;
            svg += ` viewBox="0 0 ${viewBoxWidth} ${viewBoxHeight}"`;
            svg += ` version="1.1"`;
            svg += ` xml:space="preserve"`;
            svg += ` style="shape-rendering:geometricPrecision; text-rendering:geometricPrecision; image-rendering:optimizeQuality; fill-rule:evenodd; clip-rule:evenodd; overflow:visible">\n`;
            
            // Add defs section for patterns, gradients, clipPaths
            svg += `  <defs>\n`;
            
            // Add material patterns if available
            const materialPatterns = await this._generateMaterialPatterns();
            if (materialPatterns) {
                svg += materialPatterns;
            }
            
            // Add fonts if embedding
            if (config.embedFonts) {
                const fontDefs = await this._generateFontDefs();
                if (fontDefs) {
                    svg += fontDefs;
                }
            }
            
            svg += `  </defs>\n`;
            
            // Add main group
            svg += `  <g id="design-layer">\n`;
            
            // Add background if requested
            if (config.includeBackground) {
                svg += `    <rect x="0" y="0" width="${viewBoxWidth}" height="${viewBoxHeight}" fill="#FFFFFF"/>\n`;
            }
            
            // Add logo layer
            if (logoContainer) {
                const logoSVG = await this._processLogoLayer(logoContainer, config);
                svg += logoSVG;
            }
            
            // Add text layer
            if (textContainer) {
                const textSVG = await this._processTextLayer(textContainer, config);
                svg += textSVG;
            }
            
            svg += `  </g>\n`;
            svg += `</svg>`;
            
            return svg;
        },
        
        /**
         * Process logo layer with materials and colors
         */
        _processLogoLayer: async function(logoContainer, config) {
            let logoSVG = '';
            
            // Find the logo SVG element
            const logoElement = logoContainer.querySelector('svg');
            if (!logoElement) {
                return logoSVG;
            }
            
            logoSVG += `    <!-- Logo Layer -->\n`;
            logoSVG += `    <g id="logo-layer">\n`;
            
            // Clone and process the logo SVG
            const clonedLogo = logoElement.cloneNode(true);
            
            // Get current material and color
            const currentMaterial = window.FSC?.currentMaterial || '';
            const currentColor = window.FSC?.currentColor || '#000000';
            const colorValue = this._getColorValue(currentColor);
            
            // Get stroke width from template or default
            const strokeWidth = this._getStrokeWidth() || 24;
            
            // Process all paths in the logo
            const paths = clonedLogo.querySelectorAll('path, rect, circle, ellipse, polygon, polyline');
            paths.forEach((path, index) => {
                // Set fill color
                path.setAttribute('fill', colorValue);
                path.setAttribute('fill-rule', 'evenodd');
                
                // Set stroke based on material
                if (currentMaterial && currentMaterial !== 'None' && currentMaterial !== 'Solid') {
                    // Use material pattern as stroke
                    path.setAttribute('stroke', 'url(#material-stroke-pattern)');
                    path.setAttribute('stroke-width', strokeWidth.toString());
                    path.setAttribute('stroke-linecap', 'round');
                    path.setAttribute('stroke-linejoin', 'round');
                    path.setAttribute('paint-order', 'stroke fill');
                    path.setAttribute('vector-effect', 'non-scaling-stroke');
                } else {
                    // No stroke for solid color
                    path.setAttribute('stroke', 'none');
                    path.setAttribute('stroke-width', '0');
                }
            });
            
            // Also process text elements with material stroke
            const textElements = clonedLogo.querySelectorAll('text');
            textElements.forEach((text, index) => {
                // Set fill color
                text.setAttribute('fill', colorValue);
                
                // Set stroke based on material
                if (currentMaterial && currentMaterial !== 'None' && currentMaterial !== 'Solid') {
                    // Use material pattern as stroke
                    text.setAttribute('stroke', 'url(#material-stroke-pattern)');
                    text.setAttribute('stroke-width', strokeWidth.toString());
                    text.setAttribute('stroke-linecap', 'round');
                    text.setAttribute('stroke-linejoin', 'round');
                    text.setAttribute('paint-order', 'stroke fill');
                    text.setAttribute('vector-effect', 'non-scaling-stroke');
                } else {
                    // No stroke for solid color
                    text.setAttribute('stroke', 'none');
                    text.setAttribute('stroke-width', '0');
                }
            });
            
            // Get the inner HTML of the processed logo
            logoSVG += `      ${clonedLogo.innerHTML}\n`;
            
            logoSVG += `    </g>\n`;
            
            return logoSVG;
        },
        
        /**
         * Process text layer with proper positioning
         */
        _processTextLayer: async function(textContainer, config) {
            let textSVG = '';
            
            textSVG += `    <!-- Text Layer -->\n`;
            textSVG += `    <g id="text-layer">\n`;
            
            // Get all text elements
            const textElements = textContainer.querySelectorAll('.fsc-text-item, [class*="text"]');
            
            textElements.forEach((textEl, index) => {
                const text = textEl.textContent || textEl.innerText;
                if (!text) return;
                
                // Get computed styles
                const computedStyle = window.getComputedStyle(textEl);
                const fontSize = parseInt(computedStyle.fontSize) || 28;
                const fontFamily = computedStyle.fontFamily || 'Arial';
                const fontWeight = computedStyle.fontWeight || 'normal';
                const color = computedStyle.color || '#000000';
                const textAlign = computedStyle.textAlign || 'center';
                
                // Get position
                const rect = textEl.getBoundingClientRect();
                const containerRect = textContainer.getBoundingClientRect();
                const x = rect.left - containerRect.left + (rect.width / 2);
                const y = rect.top - containerRect.top + fontSize;
                
                if (config.convertTextToPaths) {
                    // TODO: Convert text to paths for better compatibility
                    textSVG += `      <!-- Text converted to path -->\n`;
                } else {
                    // Keep as text element
                    textSVG += `      <text x="${x}" y="${y}"`;
                    textSVG += ` font-family="${fontFamily}"`;
                    textSVG += ` font-size="${fontSize}"`;
                    textSVG += ` font-weight="${fontWeight}"`;
                    textSVG += ` fill="${color}"`;
                    textSVG += ` text-anchor="middle"`;
                    textSVG += `>${this._escapeXML(text)}</text>\n`;
                }
            });
            
            textSVG += `    </g>\n`;
            
            return textSVG;
        },
        
        /**
         * Generate material pattern definitions
         */
        _generateMaterialPatterns: async function() {
            let patterns = '';
            
            // Get available materials from FSC
            const materials = window.FSC?.materialsMap || {};
            const currentMaterial = window.FSC?.currentMaterial || '';
            const materialUrl = window.FSC?.currentMaterialUrl || '';
            
            // Only generate pattern for the currently selected material
            if (currentMaterial && currentMaterial !== 'None' && currentMaterial !== 'Solid' && materialUrl) {
                try {
                    // Convert material image to base64 for better embedding
                    const base64Image = await this._imageToBase64(materialUrl);
                    
                    // Create pattern for stroke (outline)
                    patterns += `    <pattern id="material-stroke-pattern" patternUnits="userSpaceOnUse" x="0" y="0" width="100" height="100" preserveAspectRatio="xMidYMid slice">\n`;
                    patterns += `      <image xlink:href="${base64Image}" x="0" y="0" width="100" height="100" preserveAspectRatio="xMidYMid slice"/>\n`;
                    patterns += `    </pattern>\n`;
                } catch (error) {
                    console.warn('Failed to embed material pattern:', error);
                    // Fallback to URL reference
                    patterns += `    <pattern id="material-stroke-pattern" patternUnits="userSpaceOnUse" x="0" y="0" width="100" height="100">\n`;
                    patterns += `      <image xlink:href="${materialUrl}" x="0" y="0" width="100" height="100"/>\n`;
                    patterns += `    </pattern>\n`;
                }
            }
            
            return patterns;
        },
        
        /**
         * Convert image URL to base64
         */
        _imageToBase64: function(url) {
            return new Promise((resolve, reject) => {
                // If already base64, return as-is
                if (url.startsWith('data:')) {
                    resolve(url);
                    return;
                }
                
                const img = new Image();
                img.crossOrigin = 'Anonymous';
                
                img.onload = function() {
                    const canvas = document.createElement('canvas');
                    canvas.width = img.width;
                    canvas.height = img.height;
                    const ctx = canvas.getContext('2d');
                    ctx.drawImage(img, 0, 0);
                    try {
                        const dataUrl = canvas.toDataURL('image/png');
                        resolve(dataUrl);
                    } catch (e) {
                        // CORS issue, use original URL
                        resolve(url);
                    }
                };
                
                img.onerror = function() {
                    // Can't load image, use original URL
                    resolve(url);
                };
                
                img.src = url;
            });
        },
        
        /**
         * Generate font definitions for embedding
         */
        _generateFontDefs: async function() {
            let fontDefs = '';
            
            // TODO: Implement font embedding using @font-face or base64
            // This requires converting web fonts to SVG fonts or embedding as WOFF2
            
            return fontDefs;
        },
        
        /**
         * Get color value from color name or hex
         */
        _getColorValue: function(color) {
            if (!color) return '#000000';
            
            // If it's already a hex color, return it
            if (color.startsWith('#')) return color;
            
            // Try to get from FSC color map
            const colorMap = window.FSC?.colorMap || {};
            return colorMap[color] || '#000000';
        },
        
        /**         * Get stroke width from template data
         */
        _getStrokeWidth: function() {
            // Try to get from template data
            const templateData = window.FSC?._cachedTemplateData;
            if (templateData && templateData.elements) {
                const logoElement = templateData.elements.find(el => el.type === 'logo');
                if (logoElement && logoElement.properties && logoElement.properties.logoStrokeWidth !== undefined) {
                    return parseFloat(logoElement.properties.logoStrokeWidth) || 24;
                }
            }
            
            // Try to get from DOM input
            const widthInput = document.querySelector('#fsc-logo-outline-width');
            if (widthInput && widthInput.value) {
                return parseFloat(widthInput.value) || 24;
            }
            
            // Default value
            return 24;
        },
        
        /**         * Escape XML special characters
         */
        _escapeXML: function(str) {
            return String(str)
                .replace(/&/g, '&amp;')
                .replace(/</g, '&lt;')
                .replace(/>/g, '&gt;')
                .replace(/"/g, '&quot;')
                .replace(/'/g, '&apos;');
        },
        
        /**
         * Download the SVG file
         */
        downloadSVG: async function(filename = 'freight-sign-design.svg') {
            try {
                const svgContent = await this.exportDesign({
                    dpi: 300,
                    convertTextToPaths: false,
                    embedFonts: true
                });
                
                // Create blob and download
                const blob = new Blob([svgContent], { type: 'image/svg+xml' });
                const url = URL.createObjectURL(blob);
                
                const link = document.createElement('a');
                link.href = url;
                link.download = filename;
                document.body.appendChild(link);
                link.click();
                document.body.removeChild(link);
                
                // Clean up
                setTimeout(() => URL.revokeObjectURL(url), 100);
                
                console.log('✅ SVG downloaded:', filename);
                return true;
                
            } catch (error) {
                console.error('❌ SVG download failed:', error);
                return false;
            }
        },
        
        /**
         * Get SVG as data URL for preview/storage
         */
        getSVGDataURL: async function() {
            try {
                const svgContent = await this.exportDesign({
                    dpi: 150, // Lower DPI for preview
                    convertTextToPaths: false
                });
                
                // Convert to data URL
                const dataUrl = 'data:image/svg+xml;base64,' + btoa(unescape(encodeURIComponent(svgContent)));
                return dataUrl;
                
            } catch (error) {
                console.error('❌ Failed to generate SVG data URL:', error);
                return null;
            }
        }
    };
    
    console.log('✅ SVG Export module loaded');
    
})();
